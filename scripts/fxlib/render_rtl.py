"""Generated RTL: the effect bank, the router's patch header, contract wrappers."""

from __future__ import annotations

from typing import List, Sequence, Tuple

from . import routermap as rm
from .spec import Spec

Stage = rm.Stage


def _bank_instance(spec: Spec, fx_id: int) -> str:
    n = spec.name
    return f"""\
    // ---- {n} (id {fx_id}) ----------------------------------------------
    logic [`PARAM_BUS_WIDTH-1:0]     {n}_params;
    logic signed [`SAMPLE_WIDTH-1:0] {n}_out;
    logic                            {n}_out_valid;
    wire                             {n}_sel = (fx_sel == `FX_{n.upper()});

    always_ff @(posedge clk) begin
        if (!rst_n)
            {n}_params <= '0;
        else if (fx_params_load && {n}_sel)
            {n}_params <= fx_params;
    end

    {spec.top_module} u_{n} (
        .clk              (clk),
        .rst_n            (rst_n),
        .sample_in        (fx_sample),
        .sample_in_valid  (fx_valid && {n}_sel),
        .params           ({n}_params),
        .sample_out       ({n}_out),
        .sample_out_valid ({n}_out_valid)
    );
"""


def effect_bank(effects: Sequence[Tuple[Spec, int]]) -> str:
    instances = "\n".join(_bank_instance(spec, fx_id) for spec, fx_id in effects)
    cases = "\n".join(
        f"            {('`FX_' + spec.name.upper() + ':'):<16} begin fx_result = {spec.name}_out; "
        f"fx_result_valid = {spec.name}_out_valid; end"
        for spec, _ in effects
    )
    return f"""\
`timescale 1ns / 1ps
`include "effect_contract.svh"
`include "router_patch.svh"

// effect_bank.sv - GENERATED by scripts/fx.py from effects/registry.json, do not edit.
//
// One instance of every effect, addressed by router id. Same behaviour as
// VerilogSim's hand-written rtl/router/effect_bank.sv:
//
//   * Every effect sees fx_sample, but only the one selected by fx_sel gets the
//     valid strobe, so the others' state (delay lines, LFO phase) advances only
//     on samples actually routed through them.
//   * Params are latched per effect on fx_params_load, one clock before the
//     strobe, and held until that effect is dispatched again: an effect may read
//     its params on any clock.
//
// One addition: an id with no instance (a retired effect, or a gap in the ids)
// passes the sample straight through in the same clock, rather than leaving the
// router to time out on an effect that does not exist.

module effect_bank (
    input  logic                             clk,
    input  logic                             rst_n,

    input  logic [`ROUTER_ID_W-1:0]          fx_sel,
    input  logic [`PARAM_BUS_WIDTH-1:0]      fx_params,
    input  logic                             fx_params_load,
    input  logic signed [`SAMPLE_WIDTH-1:0]  fx_sample,
    input  logic                             fx_valid,

    output logic signed [`SAMPLE_WIDTH-1:0]  fx_result,
    output logic                             fx_result_valid
);

{instances}
    always_comb begin
        case (fx_sel)
{cases}
            {"default:":<16} begin fx_result = fx_sample; fx_result_valid = fx_valid; end
        endcase
    end

endmodule
"""


def router_patch_svh(effects: Sequence[Tuple[Spec, int]], preset_name: str, preset_rel: str,
                     power_on: Sequence[Tuple[str, Stage]]) -> str:
    names = ["END"] + [spec.name.upper() for spec, _ in effects]
    width = max(len(n) for n in names)
    max_id = max((fx_id for _, fx_id in effects), default=0)
    lines = [
        "// router_patch.svh - GENERATED by scripts/fx.py, do not edit.",
        "//",
        f"// Power-on patch: {preset_name} ({preset_rel})",
        "// Regenerate with: python3 scripts/fx.py gen",
        "// The memory map is documented in scripts/fxlib/routermap.py.",
        "",
        "`ifndef ROUTER_PATCH_SVH",
        "`define ROUTER_PATCH_SVH",
        "",
        f"`define ROUTER_ID_W        {rm.ID_W}",
        "// Highest id in use: routing.sv skips any id above it.",
        f"`define ROUTER_N_FX        {max_id}",
        f"`define ROUTER_SLOTS       {rm.SLOTS}",
        f"`define ROUTER_RAM_AW      {rm.RAM_AW}",
        f"`define ROUTER_CTRL_WORD   {rm.CTRL_WORD}",
        f"`define ROUTER_STATUS_WORD {rm.STATUS_WORD}",
        f"`define ROUTER_BANK0_WORD  {rm.BANK_BASE[0]}",
        f"`define ROUTER_BANK1_WORD  {rm.BANK_BASE[1]}",
        f"`define ROUTER_SLOT_WORDS  {rm.SLOT_WORDS}",
        f"`define ROUTER_PARAM_WORDS {rm.PARAM_WORDS}",
        "",
        f"`define FX_{'END':<{width}} {rm.ID_W}'d{rm.FX_END}",
    ]
    for spec, fx_id in effects:
        lines.append(f"`define FX_{spec.name.upper():<{width}} {rm.ID_W}'d{fx_id}")

    lines += ["", "// Bank 0 at power-on (unlisted words are zero):"]
    for slot, (name, (_, bits)) in enumerate(power_on):
        lines.append(f"//   slot {slot}  {name:<{width}}  {list(bits)}")
    lines.append(f"//   slot {len(power_on)}  END")

    image = rm.power_on_image([stage for _, stage in power_on])
    body = [f"    mem[{a}] = 32'h{v:08x};" for a, v in sorted(image.items())]
    lines += ["", "`define ROUTER_PATCH_INIT \\"]
    if body:
        lines += [b + " \\" for b in body[:-1]] + [body[-1]]
    else:
        lines.append("    ;")
    lines += ["", "`endif", ""]
    return "\n".join(lines)


def wrapper(spec: Spec, knob_widths: dict) -> str:
    """<name>_top for a spec that names a core `module` instead of a `top`.

    knob_widths: core port name -> width (None if unknown, taken as 16). A knob
    on a narrower port gets its top bits if it is a q16 fraction, its low bits
    if it is a raw count (validated to fit).
    """
    n = spec.name
    params = sorted(spec.params, key=lambda p: p.index)
    width = max([len(p.name) for p in params] + [4])
    table = "\n".join(f"//   slot {p.index}  {p.name:<{width}}  {p.doc}".rstrip() for p in params)

    knob_wires = []
    conns: List[Tuple[str, str]] = []
    for contract in ("clk", "rst_n", "sample_in", "sample_in_valid"):
        port = spec.core_port(contract)
        if port is not None:
            conns.append((port, contract))
    for p in params:
        knob_wires.append(f"    wire [15:0] knob_{p.name} = `PARAM({p.index});")
        w = knob_widths.get(p.core_port)
        if w in (None, 16):
            sel = ""
        elif p.scale == "q16":
            sel = f"[15:{16 - w}]"      # a fraction: its top bits span the port's full range
        else:
            sel = f"[{w - 1}:0]"        # a count: validated to fit
        conns.append((p.core_port, f"knob_{p.name}{sel}"))
    for contract in ("sample_out", "sample_out_valid"):
        conns.append((spec.core_port(contract), contract))

    pw = max(len(port) for port, _ in conns)
    body = ",\n".join(f"        .{port:<{pw}} ({sig})" for port, sig in conns)
    unused = ""
    if spec.core_port("rst_n") is None:
        unused = (f"    // {spec.module} has no reset port; reference rst_n so lint does not flag it.\n"
                  "    wire unused_rst_n = rst_n;\n\n")
    wires = "\n".join(knob_wires)
    if wires:
        wires += "\n\n"
    return f"""\
`timescale 1ns / 1ps
`include "effect_contract.svh"

// {n}_top - GENERATED by scripts/fx.py from effects/{n}/effect.json, do not edit.
//
// Presents the effect contract (router/rtl/effect_contract.svh) and slices the
// knob bus onto {spec.module}'s ports. No DSP here.
//
{table if table else "//   (no knobs)"}

module {n}_top (
    input  logic                            clk,
    input  logic                            rst_n,
    input  logic signed [`SAMPLE_WIDTH-1:0] sample_in,
    input  logic                            sample_in_valid,
    input  logic [`PARAM_BUS_WIDTH-1:0]     params,

    output logic signed [`SAMPLE_WIDTH-1:0] sample_out,
    output logic                            sample_out_valid
);

{unused}{wires}    {spec.module} u_{n} (
{body}
    );

endmodule
"""
