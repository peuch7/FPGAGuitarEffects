"""Generated C: the router's memory map for the ARM, and the effect/knob tables."""

from __future__ import annotations

import unicodedata
from typing import List, Sequence, Tuple

from . import routermap as rm
from .spec import N_PARAMS, PARAM_MAX, Spec

# Typography that turns up in docs, spelled out for a 7-bit serial terminal.
_ASCII = {"\u2014": "-", "\u2013": "-", "\u2018": "'", "\u2019": "'", "\u201c": '"',
          "\u201d": '"', "\u00d7": "x", "\u00b1": "+/-", "\u2026": "...", "\u2192": "->"}


def c_string(text: str) -> str:
    text = "".join(_ASCII.get(ch, ch) for ch in text)
    text = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode("ascii")
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def c_double(value: float) -> str:
    text = repr(float(value))
    return text if ("." in text or "e" in text or "inf" in text) else text + ".0"


def router_map_h(effects: Sequence[Tuple[Spec, int]]) -> str:
    names = ["END"] + [spec.name.upper() for spec, _ in effects]
    width = max(len(n) for n in names)
    ids = "\n".join(
        [f"#define ROUTER_FX_{'END':<{width}} {rm.FX_END}u"]
        + [f"#define ROUTER_FX_{spec.name.upper():<{width}} {fx_id}u" for spec, fx_id in effects]
    )
    return f"""\
/* router_map.h - GENERATED by scripts/fx.py, do not edit.
 *
 * Patch memory of the FPGA effect router, as seen from the ARM through an AXI
 * BRAM Controller. `base` is that controller's address from the Vivado
 * address editor (xparameters.h: XPAR_..._BASEADDR). Same API as VerilogSim's
 * sw/router_map.h; the effect ids come from effects/registry.json.
 *
 * To change patch without a glitch:
 *   1. bank = router_active_bank(base) ^ 1
 *   2. router_write_slot() for each stage, then router_write_end()
 *   3. router_select_bank(base, bank)
 *   4. router_wait_bank(base, bank) before writing the old bank again
 *
 * The router reads CTRL once at the start of every sample, so each sample runs
 * entirely on one bank. Step 4 matters: the sample in flight when CTRL changes
 * still finishes on the old bank.
 */

#ifndef ROUTER_MAP_H
#define ROUTER_MAP_H

#include <stdint.h>

{ids}

#define ROUTER_SLOTS        {rm.SLOTS}u
#define ROUTER_CTRL_WORD    {rm.CTRL_WORD}u
#define ROUTER_STATUS_WORD  {rm.STATUS_WORD}u
#define ROUTER_BANK0_WORD   {rm.BANK_BASE[0]}u
#define ROUTER_BANK1_WORD   {rm.BANK_BASE[1]}u
#define ROUTER_SLOT_WORDS   {rm.SLOT_WORDS}u
#define ROUTER_PARAM_WORDS  {rm.PARAM_WORDS}u

#define ROUTER_STATUS_BANK(s)       (((s) >> {rm.STATUS_BANK_BIT}) & 1u)
#define ROUTER_STATUS_OVERRUN(s)    (((s) >> {rm.STATUS_OVERRUN_BIT}) & 1u)
#define ROUTER_STATUS_TIMEOUT(s)    (((s) >> {rm.STATUS_TIMEOUT_BIT}) & 1u)
#define ROUTER_STATUS_HEARTBEAT(s)  ((s) >> {rm.STATUS_HEARTBEAT_SHIFT})

static inline volatile uint32_t *router_slot(volatile uint32_t *base, unsigned bank, unsigned slot)
{{
    return base + (bank ? ROUTER_BANK1_WORD : ROUTER_BANK0_WORD) + slot * ROUTER_SLOT_WORDS;
}}

/* params[k] is knob k of the effect, as named in effects/<name>/effect.json. */
static inline void router_write_slot(volatile uint32_t *base, unsigned bank, unsigned slot,
                                     uint32_t fx_id, const uint16_t params[8])
{{
    volatile uint32_t *s = router_slot(base, bank, slot);
    for (unsigned k = 0; k < ROUTER_PARAM_WORDS; ++k)
        s[1 + k] = (uint32_t)params[2 * k] | ((uint32_t)params[2 * k + 1] << 16);
    s[0] = fx_id;
}}

static inline void router_write_end(volatile uint32_t *base, unsigned bank, unsigned slot)
{{
    router_slot(base, bank, slot)[0] = ROUTER_FX_END;
}}

static inline unsigned router_active_bank(volatile uint32_t *base)
{{
    return base[ROUTER_CTRL_WORD] & 1u;
}}

static inline void router_select_bank(volatile uint32_t *base, unsigned bank)
{{
    base[ROUTER_CTRL_WORD] = bank & 1u;
}}

/* Returns once a sample has started on `bank`. Needs audio running. */
static inline void router_wait_bank(volatile uint32_t *base, unsigned bank)
{{
    while (ROUTER_STATUS_BANK(base[ROUTER_STATUS_WORD]) != (bank & 1u))
        ;
}}

#endif /* ROUTER_MAP_H */
"""


FX_TABLE_H = f"""\
/* fx_table.h - GENERATED by scripts/fx.py, do not edit.
 *
 * Every effect in the bitstream with its knobs (effects/<name>/effect.json) and
 * the presets (presets/<name>.json). The CLI runs entirely off these tables, so a new
 * effect needs no change to sw/fx_cli.
 */

#ifndef FX_TABLE_H
#define FX_TABLE_H

#include <stdint.h>

#define FX_N_KNOBS     {N_PARAMS}u     /* knob slots per effect, 16 bits each */
#define FX_KNOB_MAX    {PARAM_MAX}u
#define FX_MAX_STAGES  {rm.MAX_STAGES}u     /* router slots minus the END slot */

typedef enum {{ FX_SCALE_RAW = 0, FX_SCALE_Q16 = 1 }} fx_scale_t;

/* natural value = (scale == FX_SCALE_Q16 ? bits / 65535.0 : bits) * factor + offset */
typedef struct {{
    const char *name;
    uint8_t     slot;
    uint8_t     scale;
    uint16_t    min;
    uint16_t    max;
    uint16_t    def;
    double      factor;
    double      offset;
    const char *unit;
    const char *doc;
}} fx_knob_t;

typedef struct {{
    const char      *name;
    uint8_t          id;          /* router id, ROUTER_FX_<NAME> in router_map.h */
    uint8_t          n_knobs;
    const fx_knob_t *knobs;
    const char      *description;
}} fx_effect_t;

typedef struct {{
    uint8_t  id;
    uint16_t knobs[FX_N_KNOBS];   /* the slot's bus, indexed by fx_knob_t.slot */
}} fx_stage_t;

typedef struct {{
    const char *name;
    const char *description;
    uint8_t     n_stages;
    fx_stage_t  stages[FX_MAX_STAGES];
}} fx_preset_t;

extern const fx_effect_t fx_effects[];
extern const unsigned    fx_n_effects;
extern const fx_preset_t fx_presets[];
extern const unsigned    fx_n_presets;
extern const char        fx_power_on_preset[];

#endif /* FX_TABLE_H */
"""


def fx_table_c(effects: Sequence[Tuple[Spec, int]],
               presets: Sequence[Tuple[str, str, List[Tuple[int, Sequence[int]]]]],
               power_on: str) -> str:
    out = [
        "/* fx_table.c - GENERATED by scripts/fx.py, do not edit. See fx_table.h. */",
        "",
        '#include "fx_table.h"',
        "",
    ]
    for spec, _ in effects:
        defaults = spec.resolve()
        out.append(f"static const fx_knob_t knobs_{spec.name}[] = {{")
        for p in sorted(spec.params, key=lambda p: p.index):
            scale = "FX_SCALE_Q16" if p.scale == "q16" else "FX_SCALE_RAW"
            out.append(
                f"    {{ {c_string(p.name)}, {p.index}, {scale}, {p.lo}, {p.hi}, {defaults[p.index]}, "
                f"{c_double(p.factor)}, {c_double(p.offset)}, {c_string(p.unit)}, {c_string(p.doc)} }},"
            )
        if not spec.params:
            out.append("    { 0 },")
        out += ["};", ""]

    out.append("const fx_effect_t fx_effects[] = {")
    for spec, fx_id in effects:
        out.append(f"    {{ {c_string(spec.name)}, {fx_id}, {len(spec.params)}, knobs_{spec.name}, "
                   f"{c_string(spec.description)} }},")
    out += ["};", f"const unsigned fx_n_effects = {len(effects)};", ""]

    out.append("const fx_preset_t fx_presets[] = {")
    for name, description, stages in presets:
        body = ", ".join(
            f"{{ {fx_id}, {{ {', '.join(str(b) for b in bits)} }} }}" for fx_id, bits in stages
        ) or "{ 0 }"
        out.append(f"    {{ {c_string(name)}, {c_string(description)}, {len(stages)}, {{ {body} }} }},")
    if not presets:
        out.append("    { 0 },")
    out += ["};", f"const unsigned fx_n_presets = {len(presets)};", "",
            f"const char fx_power_on_preset[] = {c_string(power_on)};", ""]
    return "\n".join(out)
